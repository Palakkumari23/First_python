# Python Tuple

numbers = (10, 20, 30, 40, 50)

print("Tuple:", numbers)

# Accessing element
print("First element:", numbers[0])

# Slicing
print("Sliced tuple:", numbers[1:4])

# Length
print("Length:", len(numbers))

# Count
print("Count of 20:", numbers.count(20))

# Index
print("Index of 30:", numbers.index(30))