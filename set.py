# Python Set

numbers = {10, 20, 30, 40, 50}

print("Set:", numbers)

# Add an element
numbers.add(60)
print("After add:", numbers)

# Remove an element
numbers.remove(30)
print("After remove:", numbers)

# Length of set
print("Length:", len(numbers))

# Check element
print("20 in set:", 20 in numbers)